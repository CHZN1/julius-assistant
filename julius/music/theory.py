class TheoryProblem(ValueError):
    """Something the user asked for that this module cannot compute; the message is speakable."""


# ---- notes and spelling --------------------------------------------------------------------------------------------------------------------------------------
def spell(letter_index: int, pc: int) -> str:
    letter = LETTERS[letter_index % 7]
    diff = (pc - NATURAL_PC[letter] + 6) % 12 - 6
    return letter + ("#" * diff if diff > 0 else "b" * -diff)


def parse_note(text: str) -> tuple[int, int]:
    """'F#' -> (letter index, pitch class)."""
    m = re.fullmatch(r"([A-Ga-g])(#{0,2}|b{0,2}|♯{0,2}|♭{0,2})", text.strip())
    if not m:
        raise TheoryProblem(f"I don't know the note {text!r}.")
    letter = m.group(1).upper()
    acc = sum({"#": 1, "♯": 1, "b": -1, "♭": -1}[ch] for ch in m.group(2))
    return LETTERS.index(letter), (NATURAL_PC[letter] + acc) % 12


# ---- keys and scales -----------------------------------------------------------------------------------------------------------------------------------------
@dataclass(frozen=True)
class Key:
    tonic: str
    letter: int
    pc: int
    mode: str  # a SCALES name

    @property
    def name(self) -> str:
        return f"{self.tonic} {DISPLAY.get(self.mode, self.mode)}"

    @property
    def short(self) -> str:
        return {"major": f"{self.tonic} major", "minor": f"{self.tonic} minor"}.get(
            self.mode, self.name
        )

    @property
    def seven(self) -> bool:
        return len(SCALES[self.mode]) == 7


def parse_key(text: str) -> Key:
    t = " ".join(str(text or "").replace("♯", "#").replace("♭", "b").split())
    if not t:
        raise TheoryProblem("Which key?")
    m = re.fullmatch(r"([A-Ga-g])([#b]?)\s*(.*)", t)
    if not m:
        raise TheoryProblem(f"I couldn't read the key {text!r}.")
    note = m.group(1).upper() + m.group(2)
    rest = m.group(3).strip().lower()
    rest = {"m": "minor"}.get(rest, rest)
    mode = ALIASES.get(rest, rest)
    if mode not in SCALES:
        raise TheoryProblem(
            f"I don't know the scale or mode {rest!r}. I know major, minor, dorian, phrygian, lydian, mixolydian, locrian, harmonic minor, melodic minor, pentatonic and blues."
        )
    letter, pc = parse_note(note)
    return Key(note, letter, pc, mode)


def scale_notes(key: Key) -> list[str]:
    """The scale spelled by letter (one letter per degree; the blues scale's flat fifth is spelled as a flat five)."""
    return [spell(key.letter + deg - 1, (key.pc + semi) % 12) for deg, semi in SCALES[key.mode]]


def scale_pcs(key: Key) -> list[int]:
    return [(key.pc + semi) % 12 for _, semi in SCALES[key.mode]]


def scale_midi(key: Key, base: int = 57) -> list[int]:
    """The scale ascending one octave from the tonic, tonic placed in [base-6, base+5], ending on the octave."""
    t = base - 6 + (key.pc - (base - 6)) % 12
    return [t + semi for _, semi in SCALES[key.mode]] + [t + 12]


# ---- chords --------------------------------------------------------------------------------------------------------------------------------------------------
@dataclass
class Chord:
    root: str
    root_letter: int
    root_pc: int
    quality: str
    notes: list[str]  # spelled, root position
    pcs: list[int]
    offsets: list[int]  # semitones above the root, in root position (9ths above 12)
    bass: str = ""
    roman: str = ""
    midi: list[int] = field(default_factory=list)
    label: str = ""
    degrees: list[int] = field(default_factory=list)

    @property
    def symbol(self) -> str:
        return self.root + self.quality + (f"/{self.bass}" if self.bass else "")


def build_chord(root: str, quality: str, bass: str = "") -> Chord:
    if quality not in CHORDS:
        raise TheoryProblem(f"I don't know the chord type {quality!r}.")
    letter, pc = parse_note(root)
    tones = CHORDS[quality]
    notes = [spell(letter + deg - 1, (pc + semi) % 12) for deg, semi in tones]
    c = Chord(
        spell(letter, pc),
        letter,
        pc,
        quality,
        notes,
        [(pc + semi) % 12 for _, semi in tones],
        [semi for _, semi in tones],
        degrees=[deg for deg, _ in tones],
    )
    if bass:
        bl, bpc = parse_note(bass)
        c.bass = spell(bl, bpc)
    return c


def parse_chord(token: str) -> Chord:
    t = token.strip().replace("♯", "#").replace("♭", "b")
    m = CHORD_RE.match(t)
    if not m:
        raise TheoryProblem(f"I couldn't read the chord {token!r}.")
    root = m.group(1).upper() + m.group(2)
    suffix = m.group(3)
    suffix = SUFFIX_ALIASES.get(suffix, suffix)
    if suffix == "m(add9)":
        suffix = "m"
    if suffix not in CHORDS:
        raise TheoryProblem(
            f"I don't know the chord {token!r}. I know major, minor, diminished, augmented, sus, 6, 7, maj7, m7, m7b5, dim7, 9 and add9 chords."
        )
    bass = (m.group(4) or "").upper() + (m.group(5) or "") if m.group(4) else ""
    return build_chord(root, suffix, bass)


def _quality_of(third: int, fifth: int, seventh: int | None) -> str:
    triad = {(4, 7): "", (3, 7): "m", (3, 6): "dim", (4, 8): "aug"}.get((third, fifth))
    if triad is None:
        return "?"
    if seventh is None:
        return triad
    return {
        ("", 11): "maj7",
        ("", 10): "7",
        ("m", 10): "m7",
        ("m", 11): "m(maj7)",
        ("dim", 10): "m7b5",
        ("dim", 9): "dim7",
        ("aug", 11): "aug7",
        ("aug", 10): "aug7",
    }.get((triad, seventh), "?")


def diatonic(key: Key, sevenths: bool = False) -> list[Chord]:
    """The chord on each degree of a 7-note scale, built by stacking thirds inside the scale."""
    if not key.seven:
        raise TheoryProblem(
            f"{key.name} has no stacked-thirds chords; try its parent major or minor key."
        )
    names, pcs = scale_notes(key), scale_pcs(key)
    out = []
    for i in range(7):
        idx = [i, (i + 2) % 7, (i + 4) % 7] + ([(i + 6) % 7] if sevenths else [])
        up = [(pcs[j] - pcs[i]) % 12 for j in idx]
        q = _quality_of(up[1], up[2], up[3] if sevenths else None)
        if q in ("?", "aug7"):
            q = {"aug7": "aug"}.get(q, "")
        c = build_chord(names[i], q)
        c.notes, c.pcs = [names[j] for j in idx], [pcs[j] for j in idx]
        c.roman = roman_for(c, key)
        out.append(c)
    return out


# ---- Roman numerals ------------------------------------------------------------------------------------------------------------------------------------------
def roman_for(chord: Chord, key: Key) -> str:
    """Roman numeral of a chord inside a key, e.g. 'ii7', 'V', 'bVII', 'viiø'."""
    offset = (chord.root_pc - key.pc) % 12
    seven = {
        semi: deg
        for deg, semi in (
            SCALES[key.mode]
            if key.seven
            else SCALES["minor" if "minor" in key.mode or key.mode == "blues" else "major"]
        )
    }
    acc = ""
    if offset in seven:
        deg = seven[offset]
    elif offset == 6 and 5 in seven:
        deg, acc = 4, "#"
    elif (offset + 1) % 12 in seven:
        deg, acc = seven[(offset + 1) % 12], "b"
    else:
        deg, acc = seven[(offset - 1) % 12], "#"
    q = chord.quality
    minorish = q in ("m", "m7", "m6", "m9", "m11", "m13", "m(maj7)", "dim", "m7b5", "dim7")
    numeral = ROMAN[deg - 1].lower() if minorish else ROMAN[deg - 1]
    suffix = {
        "": "",
        "m": "",
        "dim": "°",
        "aug": "+",
        "7": "7",
        "maj7": "maj7",
        "m7": "7",
        "m(maj7)": "(maj7)",
        "m7b5": "ø",
        "dim7": "°7",
        "6": "6",
        "m6": "6",
        "sus2": "sus2",
        "sus4": "sus4",
        "7sus4": "7sus4",
        "add9": "add9",
        "9": "9",
        "maj9": "maj9",
        "m9": "9",
        "5": "5",
        "11": "11",
        "m11": "11",
        "13": "13",
        "maj13": "maj13",
        "m13": "13",
        "6/9": "6/9",
        "7b9": "7b9",
        "7#9": "7#9",
        "7#11": "7#11",
        "7b13": "7b13",
        "7#5": "7#5",
        "7b5": "7b5",
        "7alt": "7alt",
        "maj7#11": "maj7#11",
    }[q]
    return f"{acc}{numeral}{suffix}"


def chord_from_roman(token: str, key: Key) -> Chord:
    m = ROMAN_RE.match(token.strip().replace("♯", "#").replace("♭", "b"))
    if not m:
        raise TheoryProblem(f"I couldn't read {token!r} as a Roman numeral chord.")
    acc, numeral, dim, ext = m.groups()
    upper = numeral.isupper()
    deg = ROMAN.index(numeral.upper()) + 1
    scale = dict(
        SCALES[key.mode] if key.seven else SCALES["major" if "major" in key.mode else "minor"]
    )
    semi = scale[deg] + {"b": -1, "#": 1, "": 0}[acc]
    pc = (key.pc + semi) % 12
    name_letter = key.letter + deg - 1
    root = spell(name_letter, pc)
    if dim in ("°", "o", "dim"):
        quality = "dim7" if ext == "7" else "dim"
    elif dim == "ø":
        quality = "m7b5"
    elif dim in ("+", "aug"):
        quality = "aug"
    elif ext in ALTERED:
        quality = ext
    elif ext in ("9", "11", "13"):
        quality = ext if upper else "m" + ext
    elif ext in ("maj9", "maj13"):
        if not upper:
            raise TheoryProblem(
                f"{token!r}: a minor numeral can't take {ext}; try m9 or m13 with a lower-case numeral."
            )
        quality = ext
    elif ext in ("6", "6/9"):
        quality = ("6" if upper else "m6") if ext == "6" else "6/9"
    elif ext in ("sus2", "sus4", "add9"):
        quality = ext
    elif ext in ("maj7", "M7"):
        quality = "maj7" if upper else "m(maj7)"
    elif ext == "7":
        quality = "7" if upper else "m7"
    else:
        quality = "" if upper else "m"
    c = build_chord(root, quality)
    c.roman = token.strip()
    return c


def is_roman(token: str) -> bool:
    return bool(ROMAN_RE.match(token.strip().replace("♯", "#").replace("♭", "b")))


# ---- progressions --------------------------------------------------------------------------------------------------------------------------------------------
def split_progression(text: str) -> list[str]:
    tokens = [t for t in re.split(r"[\s,;|>–—→-]+", (text or "").replace("->", " ")) if t]
    if not tokens:
        raise TheoryProblem("Which chords?")
    if len(tokens) > 16:
        raise TheoryProblem("That's more than 16 chords; give me a shorter progression.")
    return tokens


def infer_key(chords: list[Chord]) -> list[Key]:
    """Candidate keys (major and natural minor) ranked by how many of the chords are diatonic, best first. Ties keep a major key ahead of its relative minor only when the
    first chord is the major tonic, and a minor key ahead when the first chord is the minor tonic."""
    ranked = []
    for pc in range(12):
        for mode in ("major", "minor"):
            names = (
                [n for n in ("C", "Db", "D", "Eb", "E", "F", "F#", "G", "Ab", "A", "Bb", "B")]
                if mode == "major"
                else ["C", "C#", "D", "Eb", "E", "F", "F#", "G", "G#", "A", "Bb", "B"]
            )
            letter, _ = parse_note(names[pc])
            key = Key(names[pc], letter, pc, mode)
            triads = {(c.root_pc, c.quality) for c in diatonic(key, False)} | {
                (c.root_pc, c.quality) for c in diatonic(key, True)
            }
            fit = sum(
                1
                for c in chords
                if (c.root_pc, c.quality) in triads
                or (c.root_pc, {"7": "7"}.get(c.quality, c.quality)) in triads
            )
            start = (
                1
                if chords
                and chords[0].root_pc == pc
                and (
                    chords[0].quality in ("", "maj7", "6", "add9", "maj9")
                    if mode == "major"
                    else chords[0].quality in ("m", "m7", "m9", "m6")
                )
                else 0
            )
            end = 1 if chords and chords[-1].root_pc == pc else 0
            ranked.append((fit, start + end, mode == "major", key))
    ranked.sort(key=lambda r: (-r[0], -r[1], not r[2]))
    best = ranked[0][0]
    return [r[3] for r in ranked if r[0] == best and r[0] > 0][:3]


def analyse(text: str, key_text: str = "") -> tuple[Key, list[Chord], list[Key]]:
    """Parse a progression of Roman numerals or chord symbols. -> (key, chords with Roman numerals, other candidate keys)."""
    tokens = split_progression(text)
    key = parse_key(key_text) if key_text else None
    others: list[Key] = []
    if all(is_roman(t) for t in tokens):
        if key is None:
            raise TheoryProblem("Roman numerals need a key. Which key?")
        chords = [chord_from_roman(t, key) for t in tokens]
        return key, chords, others
    chords = [parse_chord(t) for t in tokens]
    if key is None:
        cands = infer_key(chords)
        if not cands:
            raise TheoryProblem("I couldn't find a key that fits those chords. Tell me the key.")
        key, others = cands[0], cands[1:]
    for c in chords:
        c.roman = roman_for(c, key)
    return key, chords, others


FUNCTIONS = {
    1: "tonic (home)",
    2: "supertonic (pre-dominant)",
    3: "mediant (tonic colour)",
    4: "subdominant (pre-dominant)",
    5: "dominant (tension that wants to resolve home)",
    6: "submediant (tonic colour)",
    7: "leading-tone / subtonic (dominant colour)",
}


def function_of(roman: str) -> str:
    m = re.search(r"(VII|VI|IV|V|III|II|I|vii|vi|iv|v|iii|ii|i)", roman)
    if not m:
        return ""
    return FUNCTIONS[ROMAN.index(m.group(1).upper()) + 1] + (
        " (borrowed or altered)" if roman[:1] in "b#" else ""
    )


# ---- voicings ------------------------------------------------------------------------------------------------------------------------------------------------
def _stack(c: Chord, root_midi: int) -> list[int]:
    return [root_midi + o for o in c.offsets]


def _root_midi(c: Chord, base: int = 48) -> int:
    return base + (c.root_pc - base) % 12


def _with_bass(c: Chord, midi: list[int]) -> list[int]:
    if not c.bass:
        return midi
    bpc = parse_note(c.bass)[1]
    low = min(midi)
    b = low - 1 - ((low - 1 - bpc) % 12)
    return [b] + midi


def names_for(c: Chord, midi: list[int]) -> list[str]:
    """Note names for sounding pitches, using the chord's own spelling."""
    by_pc = {pc: n for pc, n in zip(c.pcs, c.notes, strict=False)}
    if c.bass:
        by_pc.setdefault(parse_note(c.bass)[1], c.bass)
    return [by_pc.get(m % 12, spell(0, m % 12)) for m in midi]


def _compact(c: Chord) -> list[int]:
    """Chord tones folded into one octave above the root (a 9th becomes a 2nd), lowest first: the compact shape used when a progression is voiced."""
    return sorted({o % 12 for o in c.offsets})


def inversions(c: Chord, compact: bool = False) -> list[list[int]]:
    root = _root_midi(c)
    base = [root + o for o in _compact(c)] if compact else _stack(c, root)
    out = [base]
    cur = base
    for _ in range(len(base) - 1):
        cur = sorted(cur[1:] + [cur[0] + 12])
        out.append(cur)
    return out


def _upward(lo: int, tones: list[tuple[int, int]], root_pc: int) -> list[int]:
    """Stack tones (degree, semitones above the root) one above the other in the order given, the first at the lowest matching pitch at or above `lo`."""
    out: list[int] = []
    for _, semi in tones:
        pc = (root_pc + semi) % 12
        out.append(lo + (pc - lo) % 12 if not out else out[-1] + ((pc - out[-1]) % 12 or 12))
    return out


def _fit(midi: list[int], low: int, high: int) -> list[int]:
    while max(midi) > high and min(midi) - 12 >= low:
        midi = [m - 12 for m in midi]
    while min(midi) < low and max(midi) + 12 <= high:
        midi = [m + 12 for m in midi]
    return midi


def rootless(
    c: Chord, variant: str = "A", lo: int = 53, low: int = 48, high: int = 79
) -> list[int] | None:
    """A rootless voicing for the piano (the bass player has the root). A stacks the 3rd, 5th, 7th and tensions in order (3-5-7-9); B starts on the 7th (7-9-3-5). Big chords
    (six notes) also leave out the 5th. None when the chord has no 7th or tension to build on."""
    tones = sorted(
        ((d, o) for d, o in zip(c.degrees, c.offsets, strict=False) if d != 1),
        key=lambda t: (t[0], t[1]),
    )
    if len(c.offsets) >= 6:
        tones = [t for t in tones if t[0] != 5]
    if variant == "B":
        i = next((k for k, t in enumerate(tones) if t[0] == 7), None)
        if i is None:
            return None
        tones = tones[i:] + tones[:i]
    if len(tones) < 3 or not any(d >= 6 for d, _ in tones):
        return None
    return _fit(_upward(lo, tones, c.root_pc), low, high)


def _shell(c: Chord) -> list[int] | None:
    third = next((o for d, o in zip(c.degrees, c.offsets, strict=False) if d in (2, 3, 4)), None)
    seventh = next((o for d, o in zip(c.degrees, c.offsets, strict=False) if d == 7), None)
    if third is None or seventh is None:
        return None
    r = _root_midi(c)
    return [r, r + third, r + seventh]


def say_voicing(c: Chord, midi: list[int]) -> str:
    """The notes of a voicing, low to high, each name once; a doubled note is said so ("D F A, with D doubled") rather than listed twice."""
    names = names_for(c, midi)
    uniq = list(dict.fromkeys(names))
    extra = [(n, names.count(n)) for n in uniq if names.count(n) > 1]
    if not extra:
        return " ".join(uniq)
    words = {2: "doubled", 3: "tripled"}
    parts = [n + " " + words.get(k, "in " + str(k) + " octaves") for n, k in extra]
    return " ".join(uniq) + ", with " + " and ".join(parts)


def voicings(c: Chord) -> list[Chord]:
    """The usual ways to play one chord: root position, inversions and drop 2 for triads and sevenths, open (triads), shell (sevenths), and for bigger chords the spread
    root position plus rootless A and B voicings."""
    n = len(c.offsets)
    out: list[tuple[str, list[int]]] = []
    if n <= 4:
        invs = inversions(c)
        labels = ["root position", "first inversion", "second inversion", "third inversion"]
        out = [(labels[i], v) for i, v in enumerate(invs)]
        if n == 4:
            root = invs[0]
            out.append(
                ("drop 2", sorted([root[-2] - 12] + [x for i, x in enumerate(root) if i != n - 2]))
            )
        if n == 3:
            r = invs[0]
            out.append(("open", [r[0], r[2], r[1] + 12]))
    else:
        out = [("root position (spread)", _stack(c, _root_midi(c)))]
        for variant in ("A", "B"):
            v = rootless(c, variant)
            if v:
                out.append((f"rootless {variant}", v))
    sh = _shell(c)
    if sh:
        out.append(("shell (root, 3rd, 7th)", sh))
    return [replace(c, midi=_with_bass(c, midi), label=label) for label, midi in out]


def _cost(prev: list[int], new: list[int]) -> float:
    move = sum(min(abs(n - p) for p in prev) for n in new)
    return move + 0.2 * abs(min(new) - min(prev)) + 0.1 * abs(len(new) - len(prev))


def smooth(
    chords: list[Chord], low: int = 45, high: int = 76, rootless_voicings: bool = False
) -> list[Chord]:
    """Voice a progression with the least movement: each chord takes the inversion and octave nearest the one before it, all inside a comfortable range. Chords with tensions
    (9ths and up) use their compact shape; with `rootless_voicings` the piano plays only the 3rd, 5th, 7th and tensions."""
    prev: list[int] | None = None
    out = []
    for c in chords:
        compact = any(o >= 12 for o in c.offsets)
        cands = []
        if rootless_voicings:
            for variant in ("A", "B"):
                v = rootless(c, variant)
                if v:
                    cands += [
                        [x + sh for x in v]
                        for sh in (-12, 0, 12)
                        if min(v) + sh >= 48 and max(v) + sh <= 79
                    ]
        if not cands:
            for inv in inversions(c, compact):
                for shift in (-24, -12, 0, 12):
                    v = [x + shift for x in inv]
                    if min(v) >= low and max(v) <= high:
                        cands.append(v)
        if not cands:
            cands = [inversions(c, compact)[0]]
        if (
            prev is None
        ):  # start in root position (or rootless A), the octave nearest the middle of the range
            first = cands if rootless_voicings else None
            if first is None:
                root = inversions(c, compact)[0]
                first = [
                    [x + sh for x in root]
                    for sh in (-24, -12, 0, 12)
                    if min(root) + sh >= low and max(root) + sh <= high
                ] or cands
            pick = min(first, key=lambda v: abs(sum(v) / len(v) - 62))
        else:
            pick = min(cands, key=lambda v: (_cost(prev, v), v[0]))
        prev = pick
        label = "rootless, smooth voice leading" if rootless_voicings else "smooth voice leading"
        out.append(replace(c, midi=_with_bass(c, pick), label=label))
    return out


