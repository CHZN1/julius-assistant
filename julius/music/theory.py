COMMON: dict[str, list[tuple[str, list[str]]]] = {
    "major": [
        ("the pop progression", ["I", "V", "vi", "IV"]),
        ("the 50s progression", ["I", "vi", "IV", "V"]),
        ("a ii-V-I", ["ii7", "V7", "Imaj7"]),
        ("a plagal turnaround", ["I", "IV", "I", "V"]),
        ("a blues turnaround", ["I7", "IV7", "I7", "V7"]),
    ],
    "minor": [
        ("the natural-minor four", ["i", "VI", "III", "VII"]),
        ("an Andalusian descent", ["i", "VII", "VI", "V"]),
        ("a minor ii-V-i", ["iiø", "V7", "i"]),
        ("a minor plagal", ["i", "iv", "i", "v"]),
    ],
    "dorian": [("a dorian vamp", ["i7", "IV7"]), ("a dorian lift", ["i7", "ii7", "IV7", "i7"])],
    "phrygian": [("a phrygian vamp", ["i", "bII"])],
    "lydian": [("a lydian vamp", ["Imaj7", "II"])],
    "mixolydian": [("a mixolydian rock cadence", ["I", "bVII", "IV", "I"])],
}


def suggestions(key: Key) -> list[tuple[str, list[Chord]]]:
    out = []
    for name, romans in COMMON.get(key.mode, []):
        out.append((name, [chord_from_roman(r, key) for r in romans]))
    return out


# ---- everything the tool says -------------------------------------------------------------------------------------------------------------------------------
def chord_line(c: Chord) -> str:
    return f"{c.roman + ' ' if c.roman else ''}{c.symbol} = {' '.join(c.notes)}" + (
        f" (bass {c.bass})" if c.bass else ""
    )


def piano_card(
    title: str, kind: str, key_name: str, scale: list[str], chords: list[Chord]
) -> dict[str, Any]:
    """The `panel.theory` card body: all names and MIDI numbers are computed here."""
    rows = []
    for c in chords[:16]:
        midi = c.midi or _with_bass(c, _stack(c, _root_midi(c)))
        rows.append(
            {
                "symbol": c.symbol,
                "roman": c.roman,
                "label": c.label,
                "notes": names_for(c, midi)[:8],
                "midi": [int(m) for m in midi][:8],
                "root": c.root_pc,
            }
        )
    return {
        "title": title,
        "kind": kind,
        "key": key_name,
        "scale_notes": scale[:12],
        "chords": rows,
    }


@dataclass
class Result:
    facts: str
    card: dict[str, Any]


def explain_key(key: Key) -> Result:
    notes = scale_notes(key)
    lines = [f"Key: {key.name}. Scale: {' '.join(notes)}."]
    if key.seven and key.mode in MODE_DEGREE and key.mode not in ("major", "minor"):
        parent_pc = (key.pc - SCALES["major"][MODE_DEGREE[key.mode] - 1][1]) % 12
        parent = next(
            n
            for n in ("C", "Db", "D", "Eb", "E", "F", "F#", "G", "Ab", "A", "Bb", "B")
            if parse_note(n)[1] == parent_pc
        )
        lines.append(
            f"{key.name} is the {MODE_DEGREE[key.mode]}th mode of {parent} major (same notes)."
        )
    if key.mode == "major":
        rel = spell(key.letter + 5, (key.pc + 9) % 12)
        lines.append(f"Relative minor: {rel} minor (same notes).")
    if key.mode == "minor":
        rel = spell(key.letter + 2, (key.pc + 3) % 12)
        lines.append(f"Relative major: {rel} major (same notes).")
    chords: list[Chord] = []
    if key.seven:
        triads, sevenths = diatonic(key, False), diatonic(key, True)
        lines.append("Chords in the key (triad / seventh), with their jobs:")
        for t, s in zip(triads, sevenths, strict=False):
            lines.append(
                f"  {t.roman} {t.symbol} ({' '.join(t.notes)}) / {s.symbol}: {function_of(t.roman)}"
            )
        chords = smooth(triads)
        sug = suggestions(key)
        if sug:
            lines.append("Progressions that work here:")
            for name, ch in sug:
                lines.append(
                    f"  {name}: {' - '.join(c.roman for c in ch)} = {' - '.join(c.symbol for c in ch)}"
                )
        if key.mode == "minor":
            v = build_chord(spell(key.letter + 4, (key.pc + 7) % 12), "")
            lines.append(
                f"Borrowed from harmonic minor: major V ({v.symbol}: {' '.join(v.notes)}) gives a stronger pull home."
            )
    else:
        lines.append(
            f"{key.name} is a {len(notes)}-note scale; play it over the chords of its parent key."
        )
        chords = [
            Chord(
                notes[0],
                key.letter,
                key.pc,
                "",
                notes,
                scale_pcs(key),
                [],
                "",
                "",
                scale_midi(key),
                "scale",
            )
        ]
    card = piano_card(f"{key.short}: scale and chords", "key", key.name, notes, chords)
    return Result("\n".join(lines), card)


def explain_scale(key: Key) -> Result:
    notes = scale_notes(key)
    steps = [semi for _, semi in SCALES[key.mode]]
    formula = " ".join(
        {1: "H", 2: "W", 3: "W+H"}.get(b - a, str(b - a))
        for a, b in zip(steps, steps[1:] + [12], strict=False)
    )
    lines = [f"{key.name}: {' '.join(notes)} (steps: {formula}; W = whole step, H = half step)."]
    if key.mode in MODE_DEGREE and key.mode != "major":
        parent_pc = (key.pc - SCALES["major"][MODE_DEGREE[key.mode] - 1][1]) % 12
        parent = next(
            n
            for n in ("C", "Db", "D", "Eb", "E", "F", "F#", "G", "Ab", "A", "Bb", "B")
            if parse_note(n)[1] == parent_pc
        )
        lines.append(
            f"It is mode {MODE_DEGREE[key.mode]} of {parent} major: the same notes, centred on {notes[0]}."
        )
        major = scale_notes(Key(key.tonic, key.letter, key.pc, "major"))
        diff = [f"{m}->{n}" for m, n in zip(major, notes, strict=False) if m != n]
        if diff:
            lines.append(f"Compared with {key.tonic} major it changes: {', '.join(diff)}.")
    if key.seven:
        sev = diatonic(key, True)
        lines.append("Seventh chords it forms: " + ", ".join(f"{c.symbol}" for c in sev) + ".")
    chords = [
        Chord(
            notes[0],
            key.letter,
            key.pc,
            "",
            notes,
            scale_pcs(key),
            [],
            "",
            "",
            scale_midi(key),
            "scale",
        )
    ]
    card = piano_card(f"{key.name} scale", "scale", key.name, notes, chords)
    return Result("\n".join(lines), card)


def explain_chord(chord: Chord, key: Key | None = None) -> Result:
    if key:
        chord.roman = roman_for(chord, key)
    vs = voicings(chord)
    lines = [
        f"{chord.symbol}: {' '.join(chord.notes)}"
        + (f" (in {key.short}: {chord.roman}, {function_of(chord.roman)})" if key else "")
        + "."
    ]
    lines.append("Voicings (lowest to highest):")
    for v in vs:
        lines.append(f"  {v.label}: {say_voicing(v, v.midi)}")
    card = piano_card(f"{chord.symbol} voicings", "chord", key.short if key else "", [], vs)
    return Result("\n".join(lines), card)


def explain_progression(text: str, key_text: str = "") -> Result:
    key, chords, others = analyse(text, key_text)
    voiced = smooth(chords)
    lines = [
        f"Progression in {key.short}"
        + (
            f" (inferred; also fits {', '.join(k.short for k in others)})"
            if others and not key_text
            else ""
        )
        + ":"
    ]
    for c in chords:
        lines.append(f"  {chord_line(c)}: {function_of(c.roman)}")
    lines.append(
        "Voiced with the least movement between chords (lowest to highest): "
        + " | ".join(
            f"{c.symbol} {say_voicing(c, v.midi)}" for c, v in zip(chords, voiced, strict=False)
        )
    )
    nondia = [c.symbol for c in chords if c.roman[:1] in "b#"]
    if nondia:
        lines.append(f"Chords outside the key (borrowed or altered): {', '.join(nondia)}.")
    card = piano_card(
        f"{' - '.join(c.roman for c in chords)} in {key.short}",
        "progression",
        key.name,
        scale_notes(key),
        voiced,
    )
    return Result("\n".join(lines), card)


def theory(key: str = "", progression: str = "", chord: str = "", scale: str = "") -> Result:
    """One entry point for the tool: chord first, then progression, then scale or mode, then a key overview."""
    if chord.strip():
        k = parse_key(key) if key.strip() else None
        return explain_chord(parse_chord(chord), k)
    if progression.strip():
        return explain_progression(progression, key)
    if scale.strip():
        return explain_scale(parse_key(scale))
    if key.strip():
        return explain_key(parse_key(key))
    raise TheoryProblem("Which key, scale, chord or progression?")
